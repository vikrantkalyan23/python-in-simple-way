# Arithmetic Operators

print("--------Arithmetic Operators--------")
print("Addition : ", 5 + 4)
print("Subtraction : ", 5 - 4)
print("Multiplication : ", 5 * 4)
print("Division : ", 5 / 4)
print("Floor Division : ", 5 // 4)
print("Modulus (Remainder) : ", 5 % 4)
print("Exponent : ", 5**4)

# Comparison / Relational Operators

a = 10
b = 12
print("--------Comparison / Relational Operators--------")
print("A is Equals to B :", a == b)
print("A is Not Equals to B : ", a != b)
print("A is Less than B : ", a < b)
print("A is Greater than B : ", a > b)
print("A is Less than or equals to B : ", a <= b)
print("A is Greater than or equals to B : ", a >= b)

# Assignment Operators
num_1 = 10
print("--------Assignment Operators--------")
num_1 += 5  # Addition assignment
num_1 -= 5  # Subtraction assignment
num_1 *= 5  # Multiplication assignment
num_1 %= 5  # Modulus assignment
num_1 /= 5  # Division assignment
num_1 //= 5  # Floor division assignment

# Logical Operators
cond1 = True
cond2 = False
print("--------Logical Operators--------")
print("AND operator : ", cond1 and cond2)
print("OR operator : ", cond1 or cond2)
print("NOT operator : ", not cond1 )
